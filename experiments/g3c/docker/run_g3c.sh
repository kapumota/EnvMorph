#!/bin/sh
# Plantilla de ejecución sin red; requiere montaje verificado y directorios de salida vacíos.
# Uso: sh docker/run_g3c.sh IMAGEN@sha256:DIGEST RESULTADOS_DIR CAMPAIGN_DIR harness/g3c_harness.py ...
set -eu
[ "$#" -ge 4 ] || { echo 'Faltan argumentos' >&2; exit 2; }
img="$1"; res="$2"; camp="$3"; shift 3
case "$img" in *@sha256:????????????????????????????????????????????????????????????????|sha256:????????????????????????????????????????????????????????????????) ;; *) echo 'Exija imagen o identificador por digest' >&2; exit 3;; esac
case "$res" in /*) ;; *) echo 'Resultados deben ser ruta absoluta' >&2; exit 3;; esac
case "$camp" in /*) ;; *) echo 'Campaña debe ser ruta absoluta' >&2; exit 3;; esac
[ -d "$res" ] && [ -d "$camp" ] || { echo 'Directorios de evidencia inexistentes' >&2; exit 3; }
exec docker run --rm --network none --read-only \
  --tmpfs /tmp:rw,exec,nosuid,nodev,size=512m \
  --cap-drop ALL --security-opt no-new-privileges \
  --pids-limit 256 --memory 2g --cpus 2 --user 10001:10001 \
  -v "$res":/g3c/results:rw -v "$camp":/g3c/campaign:rw \
  "$img" "$@"
